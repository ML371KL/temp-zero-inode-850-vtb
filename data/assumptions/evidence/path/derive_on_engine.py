def _ded_of(tl, rwa, inp: dict, scenario_id: str, **change) -> dict:
    """Траектория сценария: центр книги с отличиями `change` (доля η слагаемого роста, темп роста, высвобождение, год вычета
    сценария, доля роста вычетов в рублях)."""
    par = {"eta": inp["eta"], "rwa0": inp["rwa0"], "scenario": SCENARIO_DEDUCTION.get(scenario_id, 0.0)}
    par.update(change)
    return deduction_traj(tl, rwa, *deduction_fg(tl, **par))


def ded_series(tl, *, eta: float, rwa0: float, growth: float = DED_GROWTH_PER_Q, release: float = DTA_RELEASE_PER_YEAR,
               scenario=0.0, scenario_from: int = SCENARIO_DEDUCTION_FROM, by_quarter: bool = False,
               growth_share: float | None = None, asset_share: float | str | None = None) -> dict[str, list[float]]:
    """Ряды q = 0…Q на ключах пятого прохода ядра: `rub` — сумма в рублях, млрд ₽ (постоянная доля роста вычетов + высвобождение ОНА);
    `pp` — п.п. RWA (растущая часть роста вычетов + регуляторный вычет сценария); `change` — приращение постоянной части прочих
    активов к якорю, млрд ₽ (доля накопленного роста вычетов, которая — актив МСФО, оплаченный деньгами, + высвобождение ОНА теми же
    рублями); `release` — высвобождение ОНА, млрд ₽ (слагаемое (4) обеих сторон); `fixed` и `asset` — слагаемое (1) на стороне капитала
    (рублёвая доля роста вычетов) и на стороне баланса. `asset_share` по умолчанию — та же доля, что рублёвая доля роста вычетов (η либо
    `growth_share`; решение № 5, п. 3.1: одно суждение на обеих сторонах); "eta" — η; число — справочное чтение."""
    parts = deduction_parts(tl, eta=eta, rwa0=rwa0, growth=growth, release=release, by_quarter=by_quarter, growth_share=growth_share)
    ruble_share = float(eta) if growth_share is None else float(growth_share)
    share = ruble_share if asset_share is None else float(eta) if asset_share == "eta" else float(asset_share)
    out = {"rub": [0.0], "pp": [0.0], "change": [0.0], "release": [0.0], "fixed": [0.0], "asset": [0.0]}
    for q in range(1, tl.Q + 1):
        out["rub"].append(parts["fixed"][q] + parts["release"][q])
        out["pp"].append(parts["growing"][q] + scenario_at(scenario, scenario_from, tl.year(q)))
        out["change"].append(share * parts["grown_pp"][q] * rwa0 + parts["release"][q])
        out["release"].append(parts["release"][q])
        out["fixed"].append(parts["fixed"][q])
        out["asset"].append(share * parts["grown_pp"][q] * rwa0)
    return out


def _reads(tl, traj: dict, values: list[float], nd: int) -> str | None:
    """Читатель ядра (М§0.4) в каждом квартале сетки против самого ряда: None — воспроизводит до полуединицы последнего знака; иначе —
    первое расхождение словами. Год last_period — его среднее (ключ года; квартальные ключи в этом году ядро запрещает)."""
    from model.paths import Trajectory
    t = Trajectory(traj)
    last = [q for q in range(tl.Q + 1) if tl.year(q) == tl.last_year]
    for q in range(tl.Q + 1):
        y = tl.year(q)
        want = sum(values[i] for i in last) / len(last) if y == tl.last_year else values[q]
        got = t.value(y, int(tl.period(q)[-1]))
        if abs(got - want) > 0.5 * 10 ** -nd + 1e-9:
            return f"квартал {tl.period(q)}: {got} против {want}"
    return None


def compact_traj(tl, values: list[float], nd: int, like: dict | None = None, quarter_years=()) -> dict:
    """Траектория книги из ряда q = 0…Q — самая короткая, которую читатель ядра (М§0.4) прочтёт как сам ряд (до полуединицы
    последнего знака): год, который меняется внутри года, — ключами кварталов; плоский год — ключом года, а без ключа, если его
    значение дают интерполяция соседних заданных лет (правило 4) или значение первого заданного года (правило 6, начало траектории);
    год last_period — ключом года (среднее его кварталов: ключи кварталов в этом году ядро запрещает); LT — его значение, LT_from —
    last_period. `quarter_years` — годы, которые, если нужны, пишутся ключами кварталов (в траектории варианта на тех же ключах год
    меняется внутри года: путь оси-связки — ключ квартала). `like` — взять ключи этой траектории (конец оси-связки и вариант стоят на
    ключах центра). Запись сверяется чтением ядра: не воспроизводит ряд — отказ."""
    years: dict[int, list[int]] = {}
    for q in range(tl.Q + 1):
        years.setdefault(tl.year(q), []).append(q)
    r = lambda x: round(float(x), nd) + 0.0                     # noqa: E731 — ноль без знака
    mean = lambda y: r(sum(values[q] for q in years[y]) / len(years[y]))   # noqa: E731
    if like is not None:
        traj: dict = {}
        for k, v in like.items():
            if k == "LT_from":
                traj[k] = v
            elif k == "LT":
                traj[k] = mean(tl.last_year)
            elif "Q" in str(k):
                traj[k] = r(values[tl.index(str(k))])
            else:
                traj[k] = mean(int(k))
    else:
        order = list(years)
        varying = {y for y in order if y != tl.last_year and len({r(values[q]) for q in years[y]}) > 1}

        def build(given: set) -> dict:
            out: dict = {}
            for y in order:
                if y not in given:
                    continue
                if y == tl.last_year:
                    out[str(y)] = mean(y)
                elif y in varying or y in quarter_years:
                    out.update({tl.period(q): r(values[q]) for q in years[y]})
                else:
                    out[str(y)] = r(values[years[y][0]])
            out["LT"], out["LT_from"] = out[str(tl.last_year)], tl.last_year
            return out

        given = set(order)
        for y in order:                                         # слева направо: плоский год без ключа, если ряд читается и без него
            if y in varying or y == tl.last_year:
                continue
            if _reads(tl, build(given - {y}), values, nd) is None:
                given -= {y}
        traj = build(given)
    bad = _reads(tl, traj, values, nd)
    if bad:
        raise RuntimeError(f"траектория {traj} не воспроизводит ряд: {bad}")
    return traj


def fit_traj(tl, values: list[float], nd: int, centre: dict) -> dict:
    """Траектория справочного варианта на ключах центра: их ведут оси-связки, а книга варианта (центр с подменами) обязана нести
    пути связок — иначе схема отказывает. Ряд, который ключи центра не воспроизводят (второе чтение высвобождения: кварталы внутри
    года), — на ключах центра и своих: ключ года рядом с ключами его кварталов — их среднее (М§0.4: ядро читает написанное)."""
    try:
        return compact_traj(tl, values, nd, like=centre)
    except RuntimeError:
        pass
    own = compact_traj(tl, values, nd)
    years: dict[int, list[int]] = {}
    for q in range(tl.Q + 1):
        years.setdefault(tl.year(q), []).append(q)
    traj = dict(own)
    for k in centre:
        if k in traj:
            continue
        if "Q" in str(k):
            traj[k] = round(float(values[tl.index(str(k))]), nd) + 0.0
        else:                                                   # ключ года рядом с кварталами — точное среднее записанных кварталов
            qs = [tl.period(q) for q in years[int(k)]]
            traj[k] = round(sum(float(traj.get(p, round(float(values[tl.index(p)]), nd))) for p in qs) / len(qs), nd + 2) + 0.0
    order = lambda k: (9999, 9) if k in ("LT", "LT_from") else (int(str(k)[:4]), int(str(k)[-1]) if "Q" in str(k) else 0)   # noqa: E731
    out = {k: traj[k] for k in sorted((k for k in traj if k not in ("LT", "LT_from")), key=order)}
    out["LT"], out["LT_from"] = traj["LT"], traj["LT_from"]
    bad = _reads(tl, out, values, nd)                           # сверка чтением ядра: записанная траектория воспроизводит ряд
    if bad:
        raise RuntimeError(f"траектория варианта {out} не воспроизводит ряд: {bad}")
    return out


def _bundle_keys(traj: dict, tl) -> list[str]:
    """Ключи траектории, которые ведёт ось-связка: все числа, кроме ключа квартала якоря (ноль — якорь) и LT_from."""
    return [str(k) for k in traj if str(k) not in (tl.period(0), "LT_from")]


def deduction_family(book, tl, inp: dict) -> dict:
    """Всё, что стоит на пути вычета сценария и на пути постоянной части прочих активов: ключи центра по сценариям книги, концы оси
    роста вычетов и ключи вычета на концах оси доли вычета якоря (η ведёт и долю слагаемого роста — решение № 4, п. 3.3) — на ключах
    центра; ключи справочных вариантов (что вариант несёт — `carries`)."""
    ids = [str(s) for s in book.get("capital.reg_scenarios.ids")]
    base = {"eta": inp["eta"], "rwa0": inp["rwa0"]}

    def series(s: str, **change) -> dict:
        mix = change.pop("relief_mix", True)
        par = {**base, "scenario": scenario_of(book, tl, s, mix)}
        par.update(change)
        return ded_series(tl, **par)

    se = {s: series(s) for s in ids}
    have = {v["id"] for v in book.get("valuation.reference_variants")}
    inner = {"rub": set(), "pp": set(), "change": set()}       # годы, которые у вариантов меняются внутри года (кроме last_period)
    for vid, cfg in DEDUCTION_VARIANTS.items():
        if vid not in have:
            continue
        change = {k: v for k, v in cfg.items() if k != "carries"}
        for s in ids:
            e = series(s, **change)
            for kind in ("rub", "pp", "change"):
                if kind in cfg["carries"]:
                    inner[kind] |= {y for y in range(tl.anchor_year, tl.last_year)
                                    if len({round(e[kind][q], 9) for q in range(tl.Q + 1) if tl.year(q) == y}) > 1}
    rub = compact_traj(tl, se[ids[0]]["rub"], 2, quarter_years=inner["rub"])
    centre = {"rub": rub, "pp": {s: compact_traj(tl, se[s]["pp"], 6, quarter_years=inner["pp"]) for s in ids},
              "change": compact_traj(tl, se[ids[0]]["change"], 2, quarter_years=inner["change"])}
    if any(se[s]["rub"] != se[ids[0]]["rub"] for s in ids) or any(se[s]["change"] != se[ids[0]]["change"] for s in ids):
        raise RuntimeError("рублёвая часть пути вычета или путь постоянной части у сценариев разные — в листе они одни на все сценарии")

    def ends(**change) -> dict:
        """Концы оси-связки: ключи вычета всех сценариев (рубли и п.п.) и путь постоянной части прочих активов (решение № 5, п. 3.1: связки
        роста вычетов и доли η ведут обе стороны) — на ключах центра."""
        out = {}
        for s in ids:
            e = series(s, **change)
            pp = compact_traj(tl, e["pp"], 6, like=centre["pp"][s])
            rb = compact_traj(tl, e["rub"], 2, like=centre["rub"])
            for n in DED_NORMS:
                out.update({f"{DED_ROOT.format(s=s, n=n)}.{k}": pp[k] for k in _bundle_keys(centre["pp"][s], tl)})
            for n in DED_NORMS:
                out.update({f"{RUB_ROOT.format(s=s, n=n)}.{k}": rb[k] for k in _bundle_keys(centre["rub"], tl)})
        ch = compact_traj(tl, series(ids[0], **change)["change"], 2, like=centre["change"])
        out.update({f"{FIXED_CHANGE}.{k}": ch[k] for k in _bundle_keys(centre["change"], tl)})
        return out

    axis = {end: ends(growth=rate) for end, rate in zip(("low", "high"), DED_GROWTH_AXIS)}         # ось роста вычетов (связка)
    share_axis = {end: ends(eta=share) for end, share in zip(("low", "high"), SHARE_AXIS)}       # ось доли вычета якоря
    ends_series = {f"growth_{end}": series(ids[0], growth=rate)["change"] for end, rate in zip(("low", "high"), DED_GROWTH_AXIS)}
    ends_series.update({f"eta_{end}": series(ids[0], eta=share)["change"] for end, share in zip(("low", "high"), SHARE_AXIS)})
    ends_series["corner_low"] = series(ids[0], eta=SHARE_AXIS[0], growth=DED_GROWTH_AXIS[0])["change"]
    variants, both = {}, {}
    for vid, cfg in DEDUCTION_VARIANTS.items():
        if vid not in have:
            continue
        change = {k: v for k, v in cfg.items() if k != "carries"}
        node = {}
        for s in ids:
            e = series(s, **change)
            for n in DED_NORMS:
                if "rub" in cfg["carries"]:
                    node[RUB_ROOT.format(s=s, n=n)] = fit_traj(tl, e["rub"], 2, centre["rub"])
                if "pp" in cfg["carries"]:
                    node[DED_ROOT.format(s=s, n=n)] = fit_traj(tl, e["pp"], 6, centre["pp"][s])
        e = series(ids[0], **change)
        if "change" in cfg["carries"]:
            node[FIXED_CHANGE] = fit_traj(tl, e["change"], 2, centre["change"])
        variants[vid] = node
        both[vid] = e
    both["centre"] = se[ids[0]]
    return {"centre": centre, "axis": axis, "share_axis": share_axis, "variants": variants, "_series": both, "_ends_series": ends_series}


def both_sides(tl, inp: dict, rub: dict, change: dict, *, asset_share: float | str | None = None, **par) -> dict:
    """Одна сумма на обе стороны, по слагаемым (решение № 4, п. 3.2 — слагаемое (4); № 5, п. 3.1 — и слагаемое (1)). По записанным
    траекториям (чтение ядра) в каждом квартале сетки, млрд ₽: слагаемое стороны — запись стороны минус формула другого слагаемого той же
    стороны; `term1` — наибольшая |слагаемое (1) капитала − слагаемое (1) баланса| (рост вычетов, создание ОНА и гудвила), `term4` — то же у
    высвобождения ОНА; `design1` — разность сторон слагаемого (1) по построению (у справочных чтений «регуляторный счёт» и «весь рост на
    балансе» — не ноль; в центре и у остальных — ноль); `sums` — суммы слагаемых обеих сторон в узловых кварталах."""
    from model.paths import Trajectory
    e = ded_series(tl, eta=inp["eta"], rwa0=inp["rwa0"], asset_share=asset_share, **par)
    t_rub, t_ch = Trajectory(rub), Trajectory(change)
    out = {"term1": 0.0, "term4": 0.0, "design1": 0.0, "sums": {}}
    marks = {tl.index(DED_GROWTH_QUARTERS[1]), tl.index(f"{DTA_RELEASE_FROM}Q1"), tl.Q - 4}
    for q in range(tl.Q + 1):
        y, n = tl.year(q), int(tl.period(q)[-1])
        if y == tl.last_year and par.get("by_quarter"):
            continue                                         # год last_period — ключом года (среднее кварталов) на обеих сторонах
        cap1, bal1 = t_rub.value(y, n) - e["release"][q], t_ch.value(y, n) - e["release"][q]
        cap4, bal4 = t_rub.value(y, n) - e["fixed"][q], t_ch.value(y, n) - e["asset"][q]
        out["design1"] = max(out["design1"], abs(e["fixed"][q] - e["asset"][q]))
        out["term1"] = max(out["term1"], abs((cap1 - bal1) - (e["fixed"][q] - e["asset"][q])))   # за вычетом разности по построению
        out["term4"] = max(out["term4"], abs(cap4 - bal4))
        if q in marks:
            out["sums"][tl.period(q)] = {"term1": [round(cap1, 2), round(bal1, 2)], "term4": [round(cap4, 2), round(bal4, 2)]}
    return out


def both_sides_error(tl, inp: dict, rub: dict, change: dict, **par) -> float:
    """Наибольшая невязка обеих сторон по двум слагаемым (центр: слагаемые (1) и (4) — одна сумма в том же квартале)."""
    b = both_sides(tl, inp, rub, change, **par)
    return max(b["term1"], b["term4"])


def step_deductions(eng: Engine, out: dict) -> None:
    """Путь вычета сценария на ключах пятого прохода ядра: рубли — deduction_rub, растущая и регуляторная части — deduction_pp;
    высвобождение ОНА на стороне баланса — путь постоянной части прочих активов. RWA модальной клетки в ключи не входят: неподвижная
    точка не нужна (RWA печатаются справочно — прежняя форма «рубли / RWA модальной клетки + п.п.» для сравнения)."""
    inp = _ded_inputs(eng)
    book = eng.current()
    ids = [str(s) for s in book.get("capital.reg_scenarios.ids")]
    ctx, cell = eng.cell()
    tl, rwa = ctx.timeline, [float(x) for x in cell.quarters["rwa"]]
    family = deduction_family(book, tl, inp)
    centre = family["centre"]
    for s in ids:
        for n in DED_NORMS:
            eng.overrides[DED_ROOT.format(s=s, n=n)] = dict(centre["pp"][s])
            eng.overrides[RUB_ROOT.format(s=s, n=n)] = dict(centre["rub"])
    eng.overrides[FIXED_CHANGE] = dict(centre["change"])
    series = family.pop("_series")
    ends_series = family.pop("_ends_series")
    se = series["centre"]
    sides = {"centre": both_sides(tl, inp, centre["rub"], centre["change"])}
    for vid, cfg in DEDUCTION_VARIANTS.items():
        node = family["variants"].get(vid)
        if node is None or "change" not in cfg["carries"]:
            continue
        change = {k: v for k, v in cfg.items() if k not in ("carries", "asset_share", "relief_mix")}
        sides[vid] = both_sides(tl, inp, node.get(RUB_ROOT.format(s=ids[0], n=DED_NORMS[0]), centre["rub"]), node[FIXED_CHANGE],
                                asset_share=cfg.get("asset_share"), **change)
    # знак суммы «постоянная часть + путь» (схема: не меньше нуля у книги и на концах осей) и якорное условие (ноль в квартале якоря)
    from model.paths import Trajectory
    level = float(eng.value("volumes.other_assets_fixed"))
    share_ax = (out.get("anchor") or {}).get("share_axis") or {
        end: next(a for a in book.get("valuation.uncertainty.axes") if a["paths"][0] == SHARE_PATHS[0])[end] for end in ("low", "high")}
    levels = {"centre": level, "growth_low": level, "growth_high": level, "eta_low": float(share_ax["low"]["volumes.other_assets_fixed"]),
              "eta_high": float(share_ax["high"]["volumes.other_assets_fixed"]), "corner_low": float(share_ax["low"]["volumes.other_assets_fixed"])}
    sign = {"centre": round(level + min(se["change"]), 2)}
    sign.update({k: round(levels[k] + min(v), 2) for k, v in ends_series.items()})
    sign.update({vid: round(level + min(series[vid]["change"]), 2) for vid, cfg in DEDUCTION_VARIANTS.items()
                 if vid in series and "change" in cfg["carries"]})
    anchor_zero = {"centre": Trajectory(centre["change"]).value(tl.anchor_year, int(tl.period(0)[-1]))}
    anchor_zero.update({vid: Trajectory(node[FIXED_CHANGE]).value(tl.anchor_year, int(tl.period(0)[-1]))
                        for vid, node in family["variants"].items() if FIXED_CHANGE in node})
    q_end, q28 = tl.Q, tl.index(DED_GROWTH_QUARTERS[1])
    pp_eq = {}                                                  # прежняя форма для сравнения: рубли / RWA модальной клетки + п.п.
    for s in ids:
        pp_s = ded_series(tl, eta=inp["eta"], rwa0=inp["rwa0"], scenario=scenario_of(book, tl, s))["pp"]
        pp_eq[s] = {tl.period(q): round(se["rub"][q] / rwa[q] + pp_s[q], 6) for q in range(tl.Q + 1)}
    relief = relief_deduction(book, tl)
    out["deductions"] = {"cell": cell.label, "eta": inp["eta"], "rwa_anchor": inp["rwa0"],
                         "growth_per_quarter": DED_GROWTH_PER_Q, "release_per_year": DTA_RELEASE_PER_YEAR,
                         "scenario_pp": {s: SCENARIO_DEDUCTION.get(s, 0.0) for s in ids if s != RELIEF_ID},
                         "relief_pp_by_year": {str(y): v for y, v in relief.items()}, "relief_return": RELIEF_DEDUCTION_RETURN,
                         "fixed_change_density": FIXED_CHANGE_DENSITY,
                         "rwa_modal": {tl.period(q): round(rwa[q], 1) for q in range(tl.Q + 1)},
                         "ruble_part": {tl.period(q): round(se["rub"][q], 2) for q in range(tl.Q + 1)},
                         "release_part": {tl.period(q): round(se["release"][q], 2) for q in range(tl.Q + 1)},
                         "asset_part": {tl.period(q): round(se["asset"][q], 2) for q in range(tl.Q + 1)},
                         "pp_equivalent_on_modal_rwa": pp_eq,
                         "both_sides": {k: {kk: (round(vv, 6) if isinstance(vv, float) else vv) for kk, vv in v.items()} for k, v in sides.items()},
                         "fixed_sum_min": sign, "fixed_sum_ok": all(v >= 0 for v in sign.values()),
                         "anchor_zero": anchor_zero, "anchor_zero_ok": all(abs(v) <= 1e-9 for v in anchor_zero.values()),
                         **family}
    worst = max(max(v["term1"], v["term4"]) for v in sides.values())
    say(f"capital.reg_scenarios.*.deduction_rub: рубли пути вычета (η {inp['eta']} × рост вычетов × RWA якоря {inp['rwa0']:.1f} + высвобождение ОНА) — "
        f"{ISSUE_FROM} {se['rub'][tl.index(ISSUE_FROM)]:.2f}, {DED_GROWTH_QUARTERS[1]} {se['rub'][q28]:.2f}, конец сетки {se['rub'][q_end]:.2f} млрд ₽ "
        f"(ключей {len(centre['rub']) - 1}); deduction_pp: " + "; ".join(f"{s} {DED_GROWTH_QUARTERS[1]} {100 * centre['pp'][s][DED_GROWTH_QUARTERS[1]]:.4f} %, "
                                                                         f"LT {100 * centre['pp'][s]['LT']:.4f} %" for s in ids)
        + f"; вычет «послабления» по годам (смесь × доля возврата): " + ", ".join(f"{y} {100 * v:.4f}" for y, v in relief.items() if v)
        + f"; {FIXED_CHANGE} (доля η роста вычетов + высвобождение ОНА): " + ", ".join(f"{k} {v}" for k, v in centre["change"].items()
                                                                                      if k not in ("LT_from",) and v)
        + f"; обе стороны по слагаемым (1) и (4): наибольшая невязка {worst:.4f} млрд ₽ ({', '.join(sides)}); суммы центра: "
        + "; ".join(f"{p}: (1) {s_['term1'][0]} / {s_['term1'][1]}, (4) {s_['term4'][0]} / {s_['term4'][1]}" for p, s_ in sides["centre"]["sums"].items())
        + f"; постоянная часть + путь не ниже {min(sign.values()):.1f} млрд ₽ (центр, концы осей, варианты); ноль в квартале якоря — "
        + ("да" if out["deductions"]["anchor_zero_ok"] else "НЕТ") + f"; RWA клетки {cell.label} {rwa[0]:.0f} → {rwa[q_end]:.0f} (справочно)")


def fees_traj(have: dict, mid: float, lt: float) -> dict:
    d = {k: float(v) for k, v in have.items() if k not in FEES_KEYS and k not in ("LT", "LT_from")}
    d.update({y: mid for y in FEES_KEYS})
    d.update({"LT": lt, "LT_from": FEES_LT_FROM})
    return d


def _fees_roots(eng: Engine, goal_mid: float, goal_lt: float, start: tuple, extra: dict | None = None) -> tuple[float, float]:
    have = eng.value("fees.growth_vs_wages")
    last = int(eng.book.get("meta.last_period")[:4])
    lt_years = tuple(range(FEES_LT_FROM, last + 1))
    goal_year = int(FEES_KEYS[-1])

    def ratio(m: float, l: float, years) -> float:
        ov = dict(extra or {})
        ov["fees.growth_vs_wages"] = fees_traj(have, m, l)
        run = eng.grid(ov)
        prob = market_prob(run)
        return sum(to_assets(eng, run, prob, "fees", y) for y in years) / len(years)

    mid, lt = start
    mid = bisect(lambda x: ratio(x, lt, (goal_year,)) - goal_mid, -0.15, 0.15, tol=1e-8)
    lt = bisect(lambda x: ratio(mid, x, lt_years) - goal_lt, -0.10, 0.10, tol=1e-8)
    return mid, lt


def step_fees(eng: Engine, out: dict) -> None:
    have = eng.value("fees.growth_vs_wages")
    mid, lt = _fees_roots(eng, FEES_TO_ASSETS, FEES_TO_ASSETS, (float(have[FEES_KEYS[0]]), float(have["LT"])))
    eng.overrides["fees.growth_vs_wages"] = fees_traj(have, mid, lt)
    out["fees"] = {"goal": FEES_TO_ASSETS, "goal_year": int(FEES_KEYS[-1]), "roots": {"mid": mid, "lt": lt}}
    say(f"fees.growth_vs_wages: {FEES_KEYS[0]}–{FEES_KEYS[-1]} {mid:+.5f}; LT {lt:+.5f}")


def opex_traj(base: dict, q3: float, q4: float, r1: float, r2: float, r3: float) -> dict:
    d = dict(base)
    year = NEAR_FACT_PERIOD[:4]
    d[f"{year}Q3"], d[f"{year}Q4"] = q3, q4
    d.update({k: r1 for k in OPEX_GROUPS[0]})
    d.update({k: r2 for k in OPEX_GROUPS[1]})
    d["LT"] = r3
    return d


def opex_goals(eng: Engine, ratio_q4: float = OPEX_Q4_RATIO) -> dict:
    """Цели кварталов года якоря: квартал с месячными фактами — месяцы × 3 / число месяцев; четвёртый — среднее первых
    трёх × сезонное отношение."""
    q3 = fact_quarter(eng, NEAR_FACT_PERIOD)["opex"]
    pnl = eng.facts.file("pnl_quarterly")["quarters"]
    year = NEAR_FACT_PERIOD[:4]
    first = [abs(float(pnl[f"{year}Q{n}"]["opex"]["v"])) for n in (1, 2)]
    mean = (sum(first) + q3) / 3
    return {"q3": q3, "q4": mean * ratio_q4, "mean_q1_q3": mean, "ratio_q4": ratio_q4, "year": sum(first) + q3 + mean * ratio_q4}


def _opex_start(eng: Engine) -> tuple:
    have = eng.value("opex.real_growth")
    year = NEAR_FACT_PERIOD[:4]
    return (float(have[f"{year}Q3"]), float(have[f"{year}Q4"]), float(have[OPEX_GROUPS[0][0]]), float(have[OPEX_GROUPS[1][0]]), float(have["LT"]))


def _opex_roots(eng: Engine, goals: dict, level: float, start: tuple, which: str = "all", extra: dict | None = None) -> tuple:
    """Корни расходов: кварталы года якоря — уровни `goals`; группы лет и LT — расходы к средним активам слоя `level`.
    `which`: all — все корни по времени; q4 — только корень 4-го квартала; group1 — только корень первой группы лет.
    `extra` — подмены справочного варианта, под которые ищутся корни."""
    base = eng.value("opex.real_growth")
    book = eng.current()
    tl_year = int(NEAR_FACT_PERIOD[:4])
    lt_years = gate_years(book)

    def run_of(roots):
        ov = dict(extra or {})
        ov["opex.real_growth"] = opex_traj(base, *roots)
        return eng.grid(ov)

    def quarter(roots, qn: int) -> float:
        run = run_of(roots)
        return layer_opex_q(eng, run, run.ctx.timeline.index(f"{tl_year}Q{qn}"))

    def ratio(roots, years) -> float:
        run = run_of(roots)
        prob = market_prob(run)
        return sum(to_assets(eng, run, prob, "opex", y) for y in years) / len(years)

    q3, q4, r1, r2, r3 = start
    if which in ("all",):
        q3 = bisect(lambda x: quarter((x, q4, r1, r2, r3), 3) - goals["q3"], -0.25, 0.25, tol=1e-6)
    if which in ("all", "q4"):
        q4 = bisect(lambda x: quarter((q3, x, r1, r2, r3), 4) - goals["q4"], -0.25, 0.35, tol=1e-6)
    if which in ("all", "group1"):
        r1 = bisect(lambda x: ratio((q3, q4, x, r2, r3), (int(OPEX_GROUPS[0][-1]),)) - level, -0.10, 0.12, tol=1e-9)
    if which == "all":
        r2 = bisect(lambda x: ratio((q3, q4, r1, x, r3), (int(OPEX_GROUPS[1][-1]),)) - level, -0.10, 0.12, tol=1e-9)
        r3 = bisect(lambda x: ratio((q3, q4, r1, r2, x), lt_years) - level, -0.06, 0.06, tol=1e-9)
    return q3, q4, r1, r2, r3


def step_opex(eng: Engine, out: dict) -> None:
    goals = opex_goals(eng)
    roots = _opex_roots(eng, goals, OPEX_TO_ASSETS, _opex_start(eng))
    eng.overrides["opex.real_growth"] = opex_traj(eng.value("opex.real_growth"), *roots)
    out["opex"] = {"goal": OPEX_TO_ASSETS, "goals_anchor_year": {k: round(v, 3) for k, v in goals.items()},
                   "roots": dict(zip(("q3", "q4", "group1", "group2", "lt"), roots))}
    say(f"opex.real_growth: {NEAR_FACT_PERIOD} {roots[0]:+.5f} (цель {goals['q3']:.1f}); 4-й квартал {roots[1]:+.5f} (цель {goals['q4']:.1f} = среднее "
        f"{goals['mean_q1_q3']:.1f} × {goals['ratio_q4']}); {OPEX_GROUPS[0][0]}–{OPEX_GROUPS[0][-1]} {roots[2]:+.5f}; "
        f"{OPEX_GROUPS[1][0]}–{OPEX_GROUPS[1][-1]} {roots[3]:+.5f}; LT {roots[4]:+.5f}")


