class NeedCore(RuntimeError):
    """Ядро не готово к выводу: нет ветви, ряда клетки или функции."""


def repo_root() -> Path:
    root = HERE
    while not (root / "model" / "book.py").exists():
        if root.parent == root:
            raise NeedCore("не найден каталог model/ выше листа — запуск из дерева репозитория")
        root = root.parent
    return root


class Engine:
    """Тонкая обёртка над ядром: книга с подменами → модальная клетка и сетка."""

    def __init__(self, book_path: Path | None, facts_dir: Path | None):
        root = repo_root()
        if str(root) not in sys.path:
            sys.path.insert(0, str(root))
        try:
            from model import book_schema, levels
            from model.book import anchor_facts, load_book, load_facts
            from model.cell import run_cell
            from model.credit import bridge_from_facts
            from model.grid import judged_cells, make_context, modal_cell, point_probabilities, run_grid
            from model.live import live_from_book
            from model.nii import solve_transmission
        except ImportError as exc:
            raise NeedCore(f"{WAVE}: {exc}") from exc
        self.levels, self.anchor_facts, self.run_cell = levels, anchor_facts, run_cell
        self.make_context, self.modal_cell, self.run_grid = make_context, modal_cell, run_grid
        self.judged_cells, self.point_probabilities = judged_cells, point_probabilities
        self.live_from_book, self.solve = live_from_book, solve_transmission
        self.BookError = book_schema.BookError
        self.facts = load_facts(facts_dir)
        self.book = load_book(book_path, facts=self.facts)
        self.bridge = bridge_from_facts(self.facts)
        self.inputs = json.loads(INPUTS.read_text(encoding="utf-8"))
        self.overrides: dict = {}                              # выведенные ключи: путь → значение
        self.evaluations = 0
        self.grids = 0

    def current(self, extra: dict | None = None):
        ov = dict(self.overrides)
        ov.update(extra or {})
        return self.book.with_overrides(ov, create=True) if ov else self.book

    def cell(self, extra: dict | None = None, key: tuple | None = None):
        """(контекст, клетка) книги с выведенными ключами и подменами `extra`; без `key` — модальная клетка."""
        book = self.current(extra)
        ctx = self.make_context(book, self.facts)
        self.evaluations += 1
        return ctx, self.run_cell(ctx, *(key or self.modal_cell(book, ctx.posterior)))

    def grid(self, extra: dict | None = None):
        book = self.current(extra)
        self.grids += 1
        return self.run_grid(book, self.facts, self.live_from_book(book, self.facts))

    def value(self, path: str):
        return copy.deepcopy(self.overrides[path]) if path in self.overrides else copy.deepcopy(self.book.get(path))


