def issue_inflow(volume: float, stay: float, distributions: float, coupon_return: float) -> float:
    """Приток капитала квартала выпуска, млрд ₽: доля денег × объём + распределения квартала + возврат лишнего купона."""
    return round(float(stay) * float(volume) + float(distributions) + float(coupon_return), 2)


def step_issue(eng: Engine, out: dict) -> None:
    """Выпуск по известной цене одним местом (решение № 4, п. 3.1): приток квартала выпуска центра, концы связок осей объёма и
    доли денег, приток справочных вариантов; чтение «вложение стоит своей цены» — арифметикой."""
    book = eng.current()
    af = eng.anchor_facts(eng.facts, book.get("nii.books"))
    n_iss = float(af.n_iss)
    adj = float(book.get(VOLUME_AXIS_PATH))
    volume = issue_volume(n_iss, adj)
    flow = {k: v for k, v in eng.value(ISSUE_FLOW).items()}
    dist = float(flow["LT"])
