def step_transmission(eng: Engine, out: dict) -> None:
    book = eng.current()
    centre = float(book.get("nii.transmission.target"))
    world, key = str(book.get("nii.transmission.level_world")), float(book.get(NIM_KEY))
    rows, drift = {}, 0.0
    ax = (out.get("realized") or {}).get("axis") or {
        end: float(next(a for a in book.get("valuation.uncertainty.axes") if a["paths"][0] == TRANSMISSION_PATH)[end]) for end in ("low", "high")}
    points = [("low", {"nii.transmission.target": ax["low"]}), ("centre", {}), ("high", {"nii.transmission.target": ax["high"]}),
              ("support_low", {"nii.transmission.target": TRANSMISSION_AXIS[0]}), ("support_high", {"nii.transmission.target": TRANSMISSION_AXIS[1]}),
              ("nim_low", {NIM_KEY: NIM_AXIS[0]}), ("nim_high", {NIM_KEY: NIM_AXIS[1]})]
    for name, ov in points:
        b = eng.current(ov)
        t = float(b.get("nii.transmission.target"))
        tr = eng.solve(b, eng.facts, eng.bridge)
        gap = _floor_headroom(book, tr)
        if not name.startswith("nim"):
            drift = max(drift, abs(float(eng.bridge.to_mgmt_nim(float(tr.nss[world]))) - key))
        rows[name] = {"target": t, "nim_key": float(b.get(NIM_KEY)), "phi": round(tr.phi, 4), "sigma0": round(tr.sigma0, 6),
                      "t_real": round(tr.t_real, 9), "solved": _solved(tr, t),
                      "nss_mgmt": {w: round(float(eng.bridge.to_mgmt_nim(v)), 5) for w, v in tr.nss.items()},
                      "pairs": {k: None if v is None else round(v, 4) for k, v in tr.pairs.items()},
                      "floor_headroom": [round(gap[0], 5), gap[1], gap[2]]}
    out["transmission"] = {"axis": [ax["low"], ax["high"]], "support": list(TRANSMISSION_AXIS), "nim_axis": list(NIM_AXIS), "level_world": world,
                           "level_world_fixed": drift < 1e-9, "rows": rows}
    say(f"nii.transmission.target: {centre} (произведение середин); ось движка {ax['low']}…{ax['high']}, носитель {TRANSMISSION_AXIS[0]}…"
        f"{TRANSMISSION_AXIS[1]}; мир уровня {world} на оси " + ("неподвижен" if drift < 1e-9 else f"УХОДИТ на {100 * drift:.4f} п.п."))
    for name, r in rows.items():
        say(f"   {name:8s} цель {r['target']:+.3f}, ключ {100 * r['nim_key']:.2f} %: φ {r['phi']:.3f}, решено: {'да' if r['solved'] else 'НЕТ'}; Nss упр.: "
            + ", ".join(f"{w} {100 * v:.2f}" for w, v in r["nss_mgmt"].items())
            + f"; запас пола спреда {100 * r['floor_headroom'][0]:+.2f} п.п. ({r['floor_headroom'][1]}, {r['floor_headroom'][2]})")


def step_corridors(eng: Engine, out: dict) -> None:
    """Коридоры гейтов по счёту ядра на сетке центральной книги (клетки положительной вероятности) и поле окна фактов."""
    run = eng.grid()
    cells = eng.judged_cells(run)                              # клетки, которые судят гейты: положительной вероятности (MODEL §3.4)
    ctx, tl = run.ctx, run.ctx.timeline
    book = ctx.book
    node = eng.levels.cir_lt_value(run)                        # цель гейта — суждение книги (устав, лист pnl): здесь только печать
    ends = [tl.quarters_of_year(y)[-1] for y in range(tl.anchor_year, tl.last_year + 1)]
    share = lambda c, q: float(c.quarters["wholesale"][q]) / (float(c.quarters["funds"][q]) + float(c.quarters["wholesale"][q]))  # noqa: E731
    anchor = share(cells[0], 0)
    high, low = max(share(c, q) for c in cells for q in ends), min(share(c, q) for c in cells for q in ends)
    wh = [math.floor((min(anchor, low) - WHOLESALE_MARGIN) * 100 + 1e-9) / 100, math.ceil((max(anchor, high) + WHOLESALE_MARGIN) * 100 - 1e-9) / 100]
    eng.overrides["checks.wholesale_share"] = wh
    pb, pb_cells = {}, {}
    for w in book.get("worlds.ids"):
        vals = [run.cell_value(c) / c.bv_v for c in cells if c.world == w]     # стоимость клетки в цене — как у гейта
        pb_cells[w] = [round(min(vals), 4), round(max(vals), 4)]
        pb[w] = [max(PB_FLOOR, math.floor(min(vals) * 20 + 1e-9) / 20), math.ceil(max(vals) * 20 - 1e-9) / 20]
    eng.overrides["checks.pb_by_world"] = pb
    shares = [c.terminal_share for c in cells if run.cell_value(c) / c.bv_v >= PB_FLOOR]
    near_zero = [c.label for c in cells if run.cell_value(c) / c.bv_v < PB_FLOOR]
    term = [math.floor(min(shares) * 20 + 1e-9) / 20, math.ceil(max(shares) * 20 - 1e-9) / 20]
    eng.overrides["checks.terminal_share"] = term
    spread = [c.roe_t - c.k_t for c in cells]
    # разрыв миров — МЕРОЙ ГЕЙТА roe_k_homogeneity (решение № 6, п. 2.4; model/checks.py): среднее «ROE − k» клеток мира, которые судит
    # гейт, с вероятностями аналитического слоя; мир без массы — простое среднее. Прежняя мера листа (простое среднее клеток) — рядом
    prob = run.layers["analytical"].prob
    by_world, by_world_plain = {}, {}
    for w in book.get("worlds.ids"):
        mine = [c for c in cells if c.world == w] or [c for c in run.cells if c.world == w]
        mass = sum(prob[c.key] for c in mine)
        by_world[w] = (sum(prob[c.key] * (c.roe_t - c.k_t) for c in mine) / mass if mass
                       else sum(c.roe_t - c.k_t for c in mine) / len(mine))
        by_world_plain[w] = sum(c.roe_t - c.k_t for c in mine) / len(mine)
    gap = max(by_world.values()) - min(by_world.values())
    gap_plain = max(by_world_plain.values()) - min(by_world_plain.values())
    rk = {"range": [math.floor(min(spread) * 100 + 1e-9) / 100, math.ceil(max(spread) * 100 - 1e-9) / 100], "max_world_gap": math.ceil(gap * 100 - 1e-9) / 100}
    eng.overrides["checks.roe_k_spread"] = rk
    hist = eng.facts.file("balance")["history"]
    loans_share = round(sum(float(hist[p]["loans"]["v"]) / float(hist[p]["iea"]["v"]) for p in WINDOW_QUARTERS) / len(WINDOW_QUARTERS), 4)
    eng.overrides["checks.window_backtest.loans_share"] = loans_share
    out["corridors"] = {"cir_lt": {"value": float(node["value"]), "target": float(node["target"]), "tolerance": float(node["tolerance"]),
                                   "years": node["years"], "modal": float(node["modal"])},
                        "wholesale_share": {"anchor": round(anchor, 4), "min": round(low, 4), "max": round(high, 4), "corridor": wh},
                        "pb_by_world": {"cells": pb_cells, "corridor": pb, "negative_cells": sum(1 for c in cells if c.v_ri < 0)},
                        "terminal_share": {"min": round(min(shares), 4), "max": round(max(shares), 4), "corridor": term, "cells": len(shares),
                                           "near_zero_cells": near_zero,
                                           "all_min": round(min(c.terminal_share for c in cells), 4),
                                           "all_max": round(max(c.terminal_share for c in cells), 4)},
                        "roe_k_spread": {"min": round(min(spread), 4), "max": round(max(spread), 4),
                                         "by_world": {w: round(v, 4) for w, v in by_world.items()}, "world_gap": round(gap, 4),
                                         "measure": "мера гейта roe_k_homogeneity: вероятности аналитического слоя по клеткам, которые судит гейт",
                                         "by_world_plain": {w: round(v, 4) for w, v in by_world_plain.items()}, "world_gap_plain": round(gap_plain, 4),
                                         "corridor": rk},
                        "window": {"loans_share": loans_share, "quarters": list(WINDOW_QUARTERS)}}
    say(f"расходы к доходам слоя за {node['years'][0]}–{node['years'][-1]} годы {100 * node['value']:.2f} % при цели книги {100 * node['target']:.1f} % ± "
        f"{100 * node['tolerance']:.1f} п.п. (цель — суждение, не выводится); модальная клетка {100 * node['modal']:.2f} %")
    say(f"checks.wholesale_share: {wh}    # доля якоря {100 * anchor:.1f} %, по клеткам на концы лет {100 * low:.1f}…{100 * high:.1f} %")
    say(f"checks.pb_by_world: {flow(pb)}    # клетки: " + "; ".join(f"{w} {v[0]:.2f}…{v[1]:.2f}" for w, v in pb_cells.items()))
    say(f"checks.terminal_share: {term}    # клетки с P/B не ниже {PB_FLOOR}: {min(shares):.2f}…{max(shares):.2f} ({len(shares)} из {len(cells)}); "
        f"клетки у нуля и на полу ({len(near_zero)}) в коридор не входят: " + (", ".join(near_zero) or "нет"))
    say(f"checks.roe_k_spread: {flow(rk)}    # клетки {100 * min(spread):.1f}…{100 * max(spread):.1f} п.п.; разрыв миров мерой гейта {100 * gap:.2f} п.п. ("
        + ", ".join(f"{w} {100 * v:+.2f}" for w, v in by_world.items()) + f"; простым средним клеток — {100 * gap_plain:.2f})")
    say(f"checks.window_backtest.loans_share: {loans_share}    # среднее концов кварталов {', '.join(WINDOW_QUARTERS)}")


def step_ends(eng: Engine, out: dict) -> None:
    """Концы осей, заданные результатом, и корни справочных вариантов — на записанных числах центра."""
    ends: dict = {}
    start = _opex_start(eng)
    goals = opex_goals(eng)
    # ось уровня расходов: сдвиг корня первой группы лет под концы оси уровня
    axis = {}
    for end, level in zip(("low", "high"), OPEX_AXIS):
        axis[end] = round(_opex_roots(eng, goals, level, start, which="group1")[2] - start[2], 4)
    ends["opex_axis"] = dict(axis, levels=list(OPEX_AXIS))
    # ось сезонного отношения расходов 4-го квартала и вариант «по всему ряду»
    q4 = {}
    for name, ratio in (("low", OPEX_Q4_AXIS[0]), ("high", OPEX_Q4_AXIS[1]), ("whole_series", OPEX_Q4_WHOLE_SERIES)):
        q4[name] = round(_opex_roots(eng, opex_goals(eng, ratio), OPEX_TO_ASSETS, start, which="q4")[1], 4)
    ends["opex_q4"] = dict(q4, ratios={"low": OPEX_Q4_AXIS[0], "high": OPEX_Q4_AXIS[1], "whole_series": OPEX_Q4_WHOLE_SERIES})
    # ось уровня комиссий и вариант «уровень года якоря»
    have = eng.value("fees.growth_vs_wages")
    centre = (float(have[FEES_KEYS[0]]), float(have["LT"]))
    fa = {}
    for end, level in zip(("low", "high"), FEES_AXIS):
        fa[end] = round(_fees_roots(eng, level, level, centre)[0] - centre[0], 4)
    ends["fees_axis"] = dict(fa, levels=list(FEES_AXIS))
    run = eng.grid()
    level0 = to_assets(eng, run, market_prob(run), "fees", run.ctx.timeline.anchor_year)
    mid, lt = _fees_roots(eng, level0, level0, centre)
