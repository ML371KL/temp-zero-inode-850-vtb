def flat(eng: Engine) -> dict[str, tuple[float, float]]:
    """Выводимые числа связанных шагов: имя → (значение, величина, к которой относится изменение)."""
    nim = float(eng.value(NIM_KEY))
    out: dict[str, tuple[float, float]] = {}
    for k, v in eng.value("regimes.near_nim_shift").items():
        if k != "LT_from":
            out[f"regimes.near_nim_shift.{k}"] = (float(v), nim)
    misc = eng.value(MISC_PATH)
    for y in (MISC_YEAR,) + misc_years(int(misc["LT_from"])):                          # ближний ключ и прямая прочих доходов: мера — 100 млрд ₽
        if y in misc:
            out[f"{MISC_PATH}.{y}"] = (float(misc[y]), 100.0)
    for path in PREMIUM_PATHS.values():
        for k, v in eng.value(path).items():
            if k != "LT_from":
                out[f"{path}.{k}"] = (float(v), 1.0)
    for k, v in eng.value("capital.n20.t2").items():
        out[f"capital.n20.t2.{k}"] = (float(v), float(v))
    for s in eng.current().get("capital.reg_scenarios.ids"):                 # путь вычета сценария: мера — сотая п.п. норматива
        path = DED_ROOT.format(s=s, n=DED_NORMS[0])
        for k, v in eng.value(path).items():
            if k != "LT_from":
                out[f"{path}.{k}"] = (float(v), 0.01)
        path = RUB_ROOT.format(s=s, n=DED_NORMS[0])                          # рубли пути вычета: мера — 100 млрд ₽
        for k, v in (eng.value(path) or {}).items():
            if k != "LT_from":
                out[f"{path}.{k}"] = (float(v), 100.0)
    for name in ("fees.growth_vs_wages", "opex.real_growth"):
        for k, v in eng.value(name).items():
            if k != "LT_from":
                out[f"{name}.{k}"] = (float(v), 1.0 + float(v))
    return out


def worst_change(a: dict, b: dict) -> tuple[float, str]:
    best = (0.0, "")
    for k, (v, scale) in b.items():
        old = a.get(k, (None, None))[0]
        change = float("inf") if old is None else abs(v - old) / abs(scale)
        if change > best[0]:
            best = (change, k)
    return best


def written(eng: Engine, steps: list[str]) -> dict:
    """Выведенные ключи с точностью записи шаблона (ключи шагов, которых в запуске не было, не пишутся)."""
    keys: dict = {}
    r = lambda d, nd: {k: (v if k == "LT_from" else round(float(v), nd)) for k, v in d.items()}  # noqa: E731
    if "anchor" in steps:
        keys["capital.rwa.density"] = dict(eng.value("capital.rwa.density"))
        keys["capital.n20.deductions_anchor"] = float(eng.value("capital.n20.deductions_anchor"))
        keys["capital.n11.gap_pp"] = float(eng.value("capital.n11.gap_pp"))
        keys["volumes.other_assets_to_loans"] = float(eng.value("volumes.other_assets_to_loans"))
        keys["volumes.other_assets_fixed"] = float(eng.value("volumes.other_assets_fixed"))
        for path in SHARE_PATHS:
            keys[path] = float(eng.value(path))
    if "payout" in steps:
        keys["dividends.policy.payout"] = dict(eng.value("dividends.policy.payout"))
    if "issue" in steps:
        keys[ISSUE_FLOW] = r(eng.value(ISSUE_FLOW), 2)
    if "relief" in steps:
        for w in RELIEF_RETURN:
            keys[f"capital.reg_scenarios.{RELIEF_ID}.{w}"] = r(eng.value(f"capital.reg_scenarios.{RELIEF_ID}.{w}"), 6)
    if "loans" in steps:
        for path in LOAN_PATHS.values():
            keys[path] = dict(eng.value(path))
    if "realized" in steps:
        keys[TRANSMISSION_PATH] = round(float(eng.value(TRANSMISSION_PATH)), 6)
    if "near" in steps:
        have = eng.value("regimes.near_nim_shift")
        d = float(have[NEAR_FACT_PERIOD])
        sig = {q: (NEAR_FADE[q] * d - float(have[q])) / SIGMA0_FADE[q] for q in SIGMA0_FADE}    # вклад σ0 — из записанной траектории
        keys["regimes.near_nim_shift"] = near_traj(round(d, 5), {q: round(v, 5) for q, v in sig.items()})
    if "misc" in steps:
        keys[MISC_PATH] = r(eng.value(MISC_PATH), 1)
    if "funds" in steps:
        for path in PREMIUM_PATHS.values():
            keys[path] = r(eng.value(path), 6)
    if "t2" in steps:
        keys["capital.n20.t2"] = r(eng.value("capital.n20.t2"), 1)
    if "deductions" in steps:
        for s in eng.current().get("capital.reg_scenarios.ids"):
            for n in DED_NORMS:
                keys[DED_ROOT.format(s=s, n=n)] = r(eng.value(DED_ROOT.format(s=s, n=n)), 6)
                keys[RUB_ROOT.format(s=s, n=n)] = r(eng.value(RUB_ROOT.format(s=s, n=n)), 2)
        keys[FIXED_CHANGE] = r(eng.value(FIXED_CHANGE), 2)
    if "fees" in steps:
        keys["fees.growth_vs_wages"] = r(eng.value("fees.growth_vs_wages"), 4)
    if "opex" in steps:
        keys["opex.real_growth"] = r(eng.value("opex.real_growth"), 4)
    return keys


