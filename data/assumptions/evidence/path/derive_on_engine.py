def avg_assets(eng: Engine, run, prob: dict, year: int) -> float:
    """Средние активы года — конвенция листа pnl: среднее четырёх квартальных средних (A_(q−1) + A_q) / 2; конец
    квартала якоря — итог баланса фактов, концы кварталов до якоря — история баланса фактов."""
    tl = run.ctx.timeline
    total0 = eng.facts.need("balance", "total_assets")
    hist = eng.facts.file("balance").get("history") or {}

    def end(q: int) -> float:
        if q == 0:
            return total0
        if q < 0:
            return float(hist[tl.period(q)]["total_assets"]["v"])
        return float(eng.levels.expect(run, prob, "assets", q))

    qs = tl.quarters_of_year(year)
    return sum((end(q - 1) + end(q)) / 2 for q in qs) / len(qs)


def to_assets(eng: Engine, run, prob: dict, name: str, year: int) -> float:
    return abs(float(eng.levels.year_flow(run, prob, name, year))) / avg_assets(eng, run, prob, year)


