def near_traj(d: float, sigma: dict | None = None, fade: dict | None = None) -> dict:
    """Ближний сдвиг маржи (MODEL §3.2; решение № 5, п. 3.5): квартал с фактами — d; далее near(q) = доля d(q) × d − доля σ0(q) × вклад
    σ0(q) (`sigma` — вклад σ0 в маржу модальной клетки по кварталам года σ0); ключ года — среднее его кварталов; с года схода — ноль.
    `fade` — свои доли сдвига d (прежняя форма книги 0.4 — NEAR_OLD_FADE, без встречной σ0)."""
    fade = NEAR_FADE if fade is None else fade
    sigma = sigma or {}
    traj = {NEAR_FACT_PERIOD: d}
    traj.update({q: round(d * share - (SIGMA0_FADE.get(q, 0.0) * float(sigma.get(q, 0.0)) if fade is NEAR_FADE else 0.0), 9)
                 for q, share in fade.items()})
    year = str(NEAR_LAST_YEAR)
    qs = [v for k, v in traj.items() if k.startswith(year)]
    traj[year] = round(sum(qs) / len(qs), 9)
    traj.update({"LT": 0.0, "LT_from": NEAR_LAST_YEAR + 1})
    return traj


def sigma0_part(eng: Engine, extra: dict | None = None) -> dict:
    """Вклад σ0 в маржу модальной клетки по кварталам года σ0 (базис движка; мост аддитивный — в базисе банка то же): маржа клетки минус
    маржа той же клетки, где σ0 действует только с последнего года сетки (nii.sigma0_from — год last_period; путь сдвига тот же)."""
    ctx, on = eng.cell(extra)
    tl = ctx.timeline
    _, off = eng.cell({**(extra or {}), "nii.sigma0_from": tl.last_year})
    return {q: float(on.quarters["nim"][tl.index(q)]) - float(off.quarters["nim"][tl.index(q)]) for q in SIGMA0_FADE}


def near_step(eng: Engine, extra: dict | None = None) -> dict:
    """Ступень маржи модальной клетки на границе года σ0 (1-й квартал года минус 4-й квартал года якоря), базис банка: клетки с путём сдвига
    `extra` и «одни книги на ставках мира» (без общего сдвига и без σ0 в ближних годах)."""
    ctx, cell = eng.cell(extra)
    tl = ctx.timeline
    q1, q0 = tl.index(next(iter(SIGMA0_FADE))), tl.index(next(iter(SIGMA0_FADE))) - 1
    _, books = eng.cell({**(extra or {}), "regimes.near_nim_shift": near_traj(0.0, fade=NEAR_OLD_FADE), "nii.sigma0_from": tl.last_year})
    return {"cell": nim_mgmt_q(eng, cell, q1) - nim_mgmt_q(eng, cell, q0), "books": nim_mgmt_q(eng, books, q1) - nim_mgmt_q(eng, books, q0),
            "quarters": [tl.period(q0), tl.period(q1)]}


def step_near(eng: Engine, out: dict) -> None:
    """Общий сдвиг d: в квартале с месячными фактами модальная клетка печатает маржу фактов; встречная σ0 — вклад σ0 в маржу модальной
    клетки в год σ0 (решение № 5, п. 3.5); оба — до неподвижной точки (путь сдвига двигает баланс клетки на второй порядок)."""
    fact = fact_quarter(eng, NEAR_FACT_PERIOD)
    d = float(eng.value("regimes.near_nim_shift").get(NEAR_FACT_PERIOD, 0.0))
    sig = {q: 0.0 for q in SIGMA0_FADE}
    ctx, cell, moves = None, None, []
    for _ in range(12):
        eng.overrides["regimes.near_nim_shift"] = near_traj(d, sig)
        ctx, cell = eng.cell()
        q1 = ctx.timeline.index(NEAR_FACT_PERIOD)
        miss = fact["nim"] - nim_mgmt_q(eng, cell, q1)
        d += miss
        new = sigma0_part(eng, {"regimes.near_nim_shift": near_traj(d, sig)})
        moved = max(abs(new[q] - sig[q]) for q in sig)
        moves.append(max(abs(miss), moved))
        sig = new
        if abs(miss) < 1e-9 and moved < 1e-9:
            break
    eng.overrides["regimes.near_nim_shift"] = near_traj(d, sig)
    ctx, cell = eng.cell()
    tl = ctx.timeline
    q1 = tl.index(NEAR_FACT_PERIOD)
    _, free = eng.cell({"regimes.near_nim_shift": near_traj(0.0)})
    last = tl.index(f"{NEAR_LAST_YEAR + 1}Q4")
    step = near_step(eng)
    old = near_step(eng, {"regimes.near_nim_shift": near_traj(d, fade=NEAR_OLD_FADE)})
    out["near"] = {"cell": cell.label, "fact_period": NEAR_FACT_PERIOD, "fact_months": fact["months"], "fact_nim": round(fact["nim"], 6),
                   "d": d, "sigma0_part": sig, "fade": NEAR_FADE, "sigma0_fade": SIGMA0_FADE, "moves": moves,
                   "nim_without_shift": round(nim_mgmt_q(eng, free, q1), 6),
                   "nii_model": round(float(cell.quarters["nii"][q1]), 2), "nii_without_shift": round(float(free.quarters["nii"][q1]), 2),
                   "nii_fact": round(fact["nii"], 2),
                   "step": {"cell": step["cell"], "books": step["books"], "old_form": old["cell"], "quarters": step["quarters"],
                            "ok": abs(step["cell"]) <= abs(step["books"]) + NEAR_STEP_TOL},
                   "path": {tl.period(q): round(nim_mgmt_q(eng, cell, q), 5) for q in range(1, last + 1)},
                   "path_without_shift": {tl.period(q): round(nim_mgmt_q(eng, free, q), 5) for q in range(1, last + 1)}}
    say(f"regimes.near_nim_shift: d = {100 * d:+.3f} п.п. (маржа {NEAR_FACT_PERIOD} по месяцам {', '.join(fact['months'])}: {100 * fact['nim']:.2f} %; клетка "
        f"{cell.label} без сдвига {100 * out['near']['nim_without_shift']:.2f} %); ЧПД квартала {out['near']['nii_model']:.1f} при {fact['nii']:.1f} по фактам; "
        "встречная σ0 (вклад σ0 в маржу клетки): " + ", ".join(f"{q} {100 * v:+.3f}" for q, v in sig.items())
        + f" п.п.; ступень маржи {step['quarters'][1]} − {step['quarters'][0]}: клетка {100 * step['cell']:+.3f} п.п., одни книги на ставках мира "
          f"{100 * step['books']:+.3f}, прежняя форма {100 * old['cell']:+.3f} — " + ("не больше книг" if out["near"]["step"]["ok"] else "БОЛЬШЕ КНИГ")
        + "; путь: " + ", ".join(f"{p} {100 * v:.2f}" for p, v in list(out["near"]["path"].items())[:10]))


def misc_years(lt_from: int) -> tuple[str, ...]:
    """Годы прямой прочих доходов: от года после ближнего ключа до года перед LT_from (у книги — 2028 и 2029)."""
    return tuple(str(y) for y in range(int(MISC_YEAR) + 1, int(lt_from)))


def misc_weight(year: str, lt_from: int) -> float:
    """Доля LT в значении прямой года `year` (у начала прямой — 1 − доля): (год − год ключа) / (LT_from − год ключа)."""
    return (int(year) - int(MISC_YEAR)) / (int(lt_from) - int(MISC_YEAR))


def misc_line(start: float, lt: float, lt_from: int, nd: int | None = 1) -> dict:
    """Прямая прочих доходов (решение № 6, п. 2.2): от `start` в году ближнего ключа к `lt` в году `lt_from` — значения лет между ними."""
    out = {}
    for y in misc_years(lt_from):
        v = start + (lt - start) * misc_weight(y, lt_from)
        out[y] = v if nd is None else round(v, nd)
    return out


def misc_traj(have: dict, key: float, nd: int | None = 1, line: dict | None = None) -> dict:
    """Траектория прочих доходов с ближним ключом года `key` и ключами прямой `line` (остальные ключи — книги); порядок ключей — годы,
    затем LT и LT_from."""
    traj = {k: v for k, v in have.items()}
    traj[MISC_YEAR] = float(key) if nd is None else round(float(key), nd)
    traj.update(line or {})
    years = sorted((k for k in traj if k not in ("LT", "LT_from")), key=str)
    return {**{k: traj[k] for k in years}, **{k: traj[k] for k in ("LT", "LT_from") if k in traj}}


