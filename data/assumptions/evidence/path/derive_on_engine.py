def misc_pair(eng: Engine, extra: dict | None = None, names=("mid",)) -> dict:
    """Ключ прочих доходов года после якоря — пара к ближнему пути маржи (решение № 4, п. 3.6; № 5, п. 3.5): уровень, при котором сумма
    «ЧПД + прочие» этого года в клетке условий окна (знаменатель окна разбора) равна середине (и краям) окна C, — при подменах `extra`
    (путь маржи справочного варианта). → {имя: корень, "_window": окно, "_s": функция суммы}."""
    import facts_check as fc                                  # окно C и форма суммы — общие с листом приёмки (строка (б))
    win = fc.window_c(eng.facts, eng.inputs["skeptic"])
    wide = fc.wide_of(eng.facts, eng.inputs)
    addback = float(eng.inputs["skeptic"]["other_provisions_addback"])
    have = eng.value(MISC_PATH)
    book = eng.current(extra)
    ctx = eng.make_context(book, eng.facts)
    key_cell = (MISC_WORLD, MISC_REGIME, eng.modal_cell(book, ctx.posterior)[2])
    tl = ctx.timeline
    qs = tl.quarters_of_year(int(MISC_YEAR))

    def s_of(x: float, nd: int | None = None) -> float:
        _, cell = eng.cell({**(extra or {}), MISC_PATH: misc_traj(have, x, nd)}, key=key_cell)
        return fc.window_sum(cell.quarters, qs, tl, wide, addback)

    roots = {name: bisect(lambda x, t=win[name]: s_of(x) - t, MISC_SEARCH[0], MISC_SEARCH[1], tol=1e-9) for name in names}
    roots.update({"_window": win, "_s": s_of, "_have": have, "_cell": key_cell, "_wide": wide, "_addback": addback})
    return roots


def near_rule_keys(eng: Engine, fade_next: float) -> dict[str, dict[str, float]]:
    """Ближние ключи книг счётом листа calib-nii/r2 (вход nii_books.near_rule) при доле остатка якоря года ближнего ключа `fade_next`
    (у года якоря — доля входа): книга с ключами лет — {год: линия окна на ключевой мира-опоры за год + доля × остаток} (актив: s − (1 − a)
    × ключевая; пассив: s, у опта в году ближнего ключа — середина s и LT опта); книга бумаг — {квартал: обращение лага книги на пути
    бэктеста} (путь: y ← y + ρ_окна × (a × ключевая + s + доля × остаток − y) от ставки 2К якоря; ключ: y_(q−1) + (y_q − y_(q−1)) / ρ_книги −
    ключевая_q). Ключевая — мира-опоры передачи по кварталам ядра. Без округления."""
    rule = eng.inputs["nii_books"]["near_rule"]
    fade = {**{str(y): float(f) for y, f in rule["fade"].items()}, MISC_YEAR: float(fade_next)}
    book = eng.current()
    books = book.get("nii.books")
    ctx = eng.make_context(book, eng.facts)
    tl = ctx.timeline
    key = ctx.worlds[str(book.get("nii.transmission.reference_world"))].key

    def year_key(year: str) -> float:
        qs = [q for q in tl.quarters_of_year(int(year)) if q >= 1]
        return sum(float(key[q]) for q in qs) / len(qs)

    out: dict[str, dict[str, float]] = {}
    for b, c in rule["books"].items():
        a, s, e = float(c["a"]), float(c["s"]), float(c["residual"])
        if b == MISC_SECURITIES:
            rho = float(books[b]["rho"])
            y, keys = float(c["rate_anchor"]), {}
            for p in (k for k in books[b]["spread"] if re.fullmatch(r"\d{4}Q[1-4]", str(k))):
                q = tl.index(p)
                y_new = y + float(c["rho_window"]) * (a * float(key[q]) + s + fade.get(p[:4], 0.0) * e - y)
                keys[p] = y + (y_new - y) / rho - float(key[q])
                y = y_new
            out[b] = keys
        elif c["side"] == "asset":
            out[b] = {yr: s - (1.0 - a) * year_key(yr) + fade[yr] * e for yr in fade}
        else:
            lt = float(rule["wholesale_lt"]) if b == MISC_WHOLESALE else s
            out[b] = {yr: ((s + lt) / 2 if b == MISC_WHOLESALE and yr == MISC_YEAR else s) + fade[yr] * e for yr in fade}
    return out


def near_bare(traj: dict) -> dict:
    """Путь общего сдвига маржи без его переходной части года ближнего ключа: ключи этого года — ноль (сдвиг d и встречная σ0 2027 года);
    ключи года якоря (квартал фактов и следующий) — путь года якоря, остаются."""
    return {k: (0.0 if str(k).startswith(MISC_YEAR) else v) for k, v in traj.items()}


def misc_parts(eng: Engine, near: dict | None = None) -> list[dict]:
    """Переходные части пути ЧПД года ближнего ключа в порядке снятия (решение № 7, п. 2.4): {part, words, overrides, shift} — подмены,
    снимающие часть (снятие накопительно: подмены частей складываются). `near` — путь общего сдвига справочного варианта (встречной σ0 у
    него нет — первая часть пуста); без него — путь центра: первые части — встречная σ0 (путь near_traj(d): те же доли d, без σ0) и сдвиг
    d года ближнего ключа (near_bare). Дальше — половина остатка якоря каждой книги с ключом года (порядок книги; у книги без остатка
    подмены пусты), книга бумаг (ключи по кварталам за вычетом разности счёта при доле остатка 0,5 и 0) и сход спреда опта (ключ года —
    LT). Перед снятием лист повторяет счётом calib-nii все ближние ключи книги: расхождение — отказ (числа входа не того якоря)."""
    centre = near is None
    near = eng.value("regimes.near_nim_shift") if centre else near
    books = eng.value("nii.books")
    rule = eng.inputs["nii_books"]["near_rule"]
    on = near_rule_keys(eng, float(rule["fade"][MISC_YEAR]))
    off = near_rule_keys(eng, 0.0)
    bad = [f"{b}.{k}: счёт {v:.6f}, книга {float(books[b]['spread'][k]):.5f}" for b, keys in on.items() for k, v in keys.items()
           if abs(v - float(books[b]["spread"][k])) > NEAR_RULE_TOL]
    if bad:
        raise RuntimeError("ближние ключи книг не воспроизводятся счётом листа calib-nii (вход nii_books.near_rule): " + "; ".join(bad[:6]))
    no_sigma = near_traj(float(near[NEAR_FACT_PERIOD])) if centre else near
    year_keys = lambda t: {k: float(v) for k, v in t.items() if str(k).startswith(MISC_YEAR)}   # noqa: E731
    parts = [{"part": "sigma0", "words": MISC_PARTS_LEAD[0][1], "overrides": {"regimes.near_nim_shift": no_sigma} if centre else {},
              "shift": {k: v - year_keys(no_sigma)[k] for k, v in year_keys(near).items()} if centre else {}},
             {"part": "d", "words": MISC_PARTS_LEAD[1][1], "shift": year_keys(no_sigma),
              "overrides": {} if near_bare(near) == near else {"regimes.near_nim_shift": near_bare(near)}}]
    for b, spec in books.items():
        if b not in on or b in (MISC_SECURITIES, MISC_WHOLESALE):
            continue
        part = on[b][MISC_YEAR] - off[b][MISC_YEAR]
        parts.append({"part": b, "words": f"половина остатка якоря книги {b}", "shift": {MISC_YEAR: part},
                      "overrides": {} if part == 0.0 else {f"nii.books.{b}.spread.{MISC_YEAR}": float(spec["spread"][MISC_YEAR]) - part}})
    sec = books[MISC_SECURITIES]["spread"]
    shift = {k: on[MISC_SECURITIES][k] - off[MISC_SECURITIES][k] for k in on[MISC_SECURITIES]}
    parts.append({"part": MISC_SECURITIES, "words": "остаток якоря книги бумаг (ключи по кварталам обращением лага)",
                  "shift": {k: v for k, v in shift.items() if v != 0.0},
                  "overrides": {f"nii.books.{MISC_SECURITIES}.spread": {k: (float(v) - shift[k] if k in shift else v) for k, v in sec.items()}}})
    wh = books[MISC_WHOLESALE]["spread"]
    parts.append({"part": MISC_WHOLESALE, "words": "сход спреда опта (середина факта якоря и LT с половиной остатка → LT)",
                  "shift": {MISC_YEAR: float(wh[MISC_YEAR]) - float(wh["LT"])},
                  "overrides": {f"nii.books.{MISC_WHOLESALE}.spread.{MISC_YEAR}": float(wh["LT"])}})
    return parts


def misc_bare_overrides(eng: Engine, near: dict | None = None) -> dict:
    """Подмены пути без всех переходных частей года ближнего ключа (сумма подмен всех частей)."""
    ov: dict = {}
    for p in misc_parts(eng, near):
        ov.update(p["overrides"])
    return ov


def misc_pairs_by_part(eng: Engine, centre: float, near: dict | None = None) -> dict:
    """Пары к переходным частям: снятие накопительно в порядке misc_parts; пара части = пара до её снятия минус пара после (что ключ года
    несёт за эту часть); сумма частей — разность пар (пара пути `centre` минус пара пути без всех частей). Часть без подмен — ноль, без счёта."""
    cum: dict = {}
    prev, rows = centre, []
    for p in misc_parts(eng, near):
        if not p["overrides"]:
            rows.append({"part": p["part"], "words": p["words"], "pair": 0.0, "after": prev, "shift": p["shift"]})
            continue
        cum.update(p["overrides"])
        got = misc_pair(eng, dict(cum))["mid"]
        rows.append({"part": p["part"], "words": p["words"], "pair": prev - got, "after": got, "shift": p["shift"]})
        prev = got
    return {"parts": rows, "bare": prev, "delta": centre - prev, "overrides": cum}


def step_misc(eng: Engine, out: dict) -> None:
    """Ближний ключ прочих доходов — пара к ближнему пути маржи: середина окна C в сумме «ЧПД + прочие» клетки условий окна; концы оси —
    края окна (решение № 4, п. 3.6; № 5, п. 3.5: подпись «пара к ближнему пути маржи; середина окна C»)."""
    pair = misc_pair(eng, names=("mid", "low", "high"))
    win, s_of, have, wide, addback = pair["_window"], pair["_s"], pair["_have"], pair["_wide"], pair["_addback"]
    roots = {name: pair[name] for name in ("mid", "low", "high")}
    tl = eng.make_context(eng.current(), eng.facts).timeline
    qs = tl.quarters_of_year(int(MISC_YEAR))
    key_cell = pair["_cell"]
    key = round(roots["mid"], 1)
    # прочие 2028–2029 годов (решение № 7, п. 2.4): прямая к LT от пары к пути центра без всех переходных частей 2027 года; начало прямой —
    # записанный ключ 2027 года минус разность пар (сумма пар по частям); справочно — форма 0.6 (минус одна пара к встречной σ0)
    by_part = misc_pairs_by_part(eng, roots["mid"])
    delta, bare_pair = by_part["delta"], by_part["bare"]
    sigma0_pair = by_part["parts"][0]["pair"]
    lt, lt_from = float(have["LT"]), int(have["LT_from"])
    years = misc_years(lt_from)
    start = key - delta
    line = misc_line(start, lt, lt_from)
    start_06 = key - sigma0_pair
    line_06 = misc_line(start_06, lt, lt_from)
    eng.overrides[MISC_PATH] = misc_traj(have, key, line=line)
    _, cell = eng.cell(key=key_cell)
    # оси-связки (MODEL §10): ось ключа 2027 года — концы ключа — края окна C тем же счётом, ключи прямой — доля (1 − w) приращения
    # ключа (разность пар вдоль оси постоянна); ось LT — концы LT — суждения книги, ключи прямой — доля w приращения LT
    book_line = {y: float(eng.overrides[MISC_PATH][y]) for y in years}
    axis_bundle, lt_bundle = {}, {}
    lt_ends = misc_axis_ends(eng, MISC_LT_PATH)
    for e in ("low", "high"):
        end = round(roots[e], 1)
        axis_bundle[e] = {f"{MISC_PATH}.{MISC_YEAR}": end,
                          **{f"{MISC_PATH}.{y}": round(book_line[y] + (end - key) * (1.0 - misc_weight(y, lt_from)), 2) for y in years}}
        lt_bundle[e] = {MISC_LT_PATH: lt_ends[e],
                        **{f"{MISC_PATH}.{y}": round(book_line[y] + (lt_ends[e] - lt) * misc_weight(y, lt_from), 2) for y in years}}
    # справочные варианты уровня прочих доходов: тот же ключ 2027 года, прямая от того же начала к своему LT
    variants = {vid: {MISC_YEAR: key, **misc_line(start, misc_variant_lt(eng, vid), lt_from)} for vid in MISC_VARIANTS}
    # справочный вариант «пары к переходным частям наследуются» (форма книги 0.6): ключ центра, прямая от ключа минус одна пара к встречной σ0
    inherited = {"id": MISC_INHERITED, "start": start_06, "line": line_06, "overrides": {f"{MISC_PATH}.{y}": v for y, v in line_06.items()}}
    # сверка: ЧПД клетки условий окна в обеих формах пути — года ближнего ключа (разность — сами переходные части) и следующего (с 2028К1
    # переходных частей нет — разность второго порядка через баланс)
    nxt = tl.quarters_of_year(int(MISC_YEAR) + 1)
    _, cell_bare = eng.cell(by_part["overrides"], key=key_cell)
    nii_y = lambda c, quarters: sum(float(c.quarters["nii"][i]) for i in quarters)   # noqa: E731
    nii_next = {"centre": nii_y(cell, nxt), "bare": nii_y(cell_bare, nxt), "difference": nii_y(cell, nxt) - nii_y(cell_bare, nxt),
                "ok": abs(nii_y(cell, nxt) - nii_y(cell_bare, nxt)) <= MISC_NEXT_TOL, "tol": MISC_NEXT_TOL}
    nii_this = {"centre": nii_y(cell, qs), "bare": nii_y(cell_bare, qs)}
    out["misc"] = {"cell": cell.label, "year": int(MISC_YEAR), "label": "пара к ближнему пути маржи; середина окна C",
                   "window": win, "wide": wide, "addback": addback, "roots": roots, "key": key,
                   "axis": {"low": round(roots["low"], 1), "high": round(roots["high"], 1)},
                   "sum_at_key": s_of(key, 1), "sum_at_axis": {e: s_of(round(roots[e], 1), 1) for e in ("low", "high")},
                   "sum_was": s_of(float(have[MISC_YEAR]), None), "was": float(have[MISC_YEAR]),
                   "nim_cell": sum(float(cell.quarters["nii"][i]) for i in qs) / (sum(float(cell.quarters["iea_avg"][i]) * tl.d(i) for i in qs)
                                                                                  / sum(tl.d(i) for i in qs)) * 365.0 / sum(tl.d(i) for i in qs),
                   "line_rule": "прямая к LT от пары к пути без всех переходных частей 2027 года: ключ 2027 года минус разность пар (сумма пар по "
                                "частям: встречная σ0, сдвиг d, половина остатка якоря книг, остаток книги бумаг, сход опта; решение № 7, п. 2.4)",
                   "pairs": by_part["parts"], "pair_bare": bare_pair, "pairs_delta": delta,
                   "pair_without_sigma0": by_part["parts"][0]["after"], "sigma0_pair": sigma0_pair, "line_start": start, "line": line,
                   "line_was": {y: have.get(y) for y in years}, "lt": lt, "lt_from": lt_from, "inherited": inherited,
                   "axis_bundle": axis_bundle, "lt_axis": lt_bundle, "variants": variants, "nii_next_year": nii_next, "nii_this_year": nii_this}
    say(f"{MISC_PATH}.{MISC_YEAR}: {key} (было {have[MISC_YEAR]}; пара к ближнему пути маржи; середина окна C): клетка {cell.label}, сумма «ЧПД + прочие» {MISC_YEAR} года в знаменателе окна "
        f"{100 * out['misc']['sum_at_key']:.3f} % = середина окна C {100 * win['mid']:.3f} % (без разового {100 * win['low']:.2f} %, с ним {100 * win['high']:.2f} %; "
        f"при прежнем ключе — {100 * out['misc']['sum_was']:.3f} %); ось {out['misc']['axis']['low']} … {out['misc']['axis']['high']}")
    say(f"   пары к переходным частям пути ЧПД {MISC_YEAR} года (снятие накопительно; пара центра {roots['mid']:.2f}): "
        + "; ".join(f"{r['part']} {r['pair']:+.2f}" for r in by_part["parts"]) + f"; сумма {delta:+.2f} → пара пути без переходных частей {bare_pair:.2f}")
    say(f"{MISC_PATH} {', '.join(years)}: прямая к LT {lt:g} от пары без переходных частей {bare_pair:.2f} (ключ {key} минус разность пар {delta:.2f}; начало "
        f"{start:.2f}): " + ", ".join(f"{y} — {line[y]}" for y in years) + " (было " + ", ".join(f"{y} — {have.get(y)}" for y in years) + "); ЧПД клетки "
        f"{cell.label}: {MISC_YEAR} — путь центра {nii_this['centre']:.1f}, без переходных частей {nii_this['bare']:.1f}; {int(MISC_YEAR) + 1} — "
        f"{nii_next['centre']:.1f} и {nii_next['bare']:.1f} (разность {nii_next['difference']:+.1f}, второй порядок — "
        + ("да" if nii_next["ok"] else f"НЕТ: больше {MISC_NEXT_TOL:g}") + "); варианты уровня: "
        + "; ".join(f"{vid} " + " / ".join(f"{v[y]}" for y in years) for vid, v in variants.items())
        + f"; вариант {MISC_INHERITED} (форма 0.6: минус пара к встречной σ0 {sigma0_pair:.2f}, начало {start_06:.2f}): "
        + " / ".join(f"{line_06[y]}" for y in years))


def premium_traj(have: dict, level: float) -> dict:
    """Траектория премии сегмента: ключ квартала с фактом — книги; далее уровень по форме; с года после формы — ноль."""
    traj = {k: v for k, v in have.items() if k not in PREMIUM_SHAPE and k not in ("LT", "LT_from")}
    traj.update({k: round(level * share, 9) for k, share in PREMIUM_SHAPE.items()})
    traj.update({"LT": 0.0, "LT_from": PREMIUM_FADE_TO})
    return traj


def _loans_to_funds(eng: Engine, year: int, extra: dict) -> tuple[float, float]:
    ctx, cell = eng.cell(extra)
    q = ctx.timeline.quarters_of_year(year)[-1]
    lf = lambda i: float(cell.quarters["loans"][i]) / float(cell.quarters["funds"][i])  # noqa: E731
    return lf(q), lf(0)


def step_funds(eng: Engine, out: dict) -> None:
    """Премия роста средств клиентов: (факт сегмента + нужда баланса) / 2; нужда — один уровень на оба сегмента."""
    facts = eng.inputs["funds_premium"]["facts"]
    have = {seg: eng.value(path) for seg, path in PREMIUM_PATHS.items()}

    def trial(levels: dict) -> dict:
        return {PREMIUM_PATHS[seg]: premium_traj(have[seg], levels[seg]) for seg in PREMIUM_PATHS}

    def ratio(level: float) -> float:
        got, anchor = _loans_to_funds(eng, NEED_YEAR, trial({seg: level for seg in PREMIUM_PATHS}))
        return got - anchor

    need = bisect(ratio, -0.25, 0.10, tol=1e-9)
    need_w = round(need, 4)
    levels = {seg: round((float(facts[seg]) + need_w) / 2, 4) for seg in PREMIUM_PATHS}
    for seg, path in PREMIUM_PATHS.items():
        eng.overrides[path] = premium_traj(have[seg], levels[seg])
    anchor = _loans_to_funds(eng, NEED_YEAR, {})[1]
    ends = (("low", {seg: float(facts[seg]) for seg in PREMIUM_PATHS}), ("high", {seg: need_w for seg in PREMIUM_PATHS}))
    # ось премии — ключи уровня; сход ведёт ось-связка роста после лет окна; справочные варианты концов оси несут всю форму
    axis = {end: {f"{PREMIUM_PATHS[seg]}.{k}": round(lvl[seg], 9) for seg in PREMIUM_PATHS for k in PREMIUM_LEVEL_KEYS} for end, lvl in ends}
    full = {end: {f"{PREMIUM_PATHS[seg]}.{k}": round(lvl[seg] * share, 9) for seg in PREMIUM_PATHS for k, share in PREMIUM_SHAPE.items()}
            for end, lvl in ends}
    # ось-связка роста после лет окна: низ — премии последнего года окна (кредиты) и уровень премии (средства) держатся до года
    # схода; верх — ноль сразу после лет окна
    last = LOAN_WINDOW_YEARS[-1]                                # шага loans в запуске нет — премии кредитов книги
    growth_axis = (out.get("loans") or {}).get("axis") or {
        "low": {f"{path}.{y}": float(eng.value(path)[last]) for path in LOAN_PATHS.values() for y in FADE_YEARS},
        "high": {f"{path}.{y}": 0.0 for path in LOAN_PATHS.values() for y in FADE_YEARS}}
    growth_axis = {end: dict(growth_axis[end]) for end in ("low", "high")}
    growth_axis["low"].update({f"{PREMIUM_PATHS[seg]}.{y}": levels[seg] for seg in PREMIUM_PATHS for y in FADE_YEARS})
    growth_axis["high"].update({f"{PREMIUM_PATHS[seg]}.{y}": 0.0 for seg in PREMIUM_PATHS for y in FADE_YEARS})
    out["funds"] = {"need_level": need_w, "need_exact": need, "facts": dict(facts), "levels": levels, "anchor_loans_to_funds": round(anchor, 6),
                    "year": NEED_YEAR, "shape": PREMIUM_SHAPE, "axis": axis, "axis_full": full, "growth_axis": growth_axis,
                    "ratio_at_need": round(ratio(need_w) + anchor, 6), "ratio_at_centre": round(_loans_to_funds(eng, NEED_YEAR, {})[0], 6),
                    "ratio_at_facts": round(_loans_to_funds(eng, NEED_YEAR, trial({seg: float(facts[seg]) for seg in PREMIUM_PATHS}))[0], 6),
                    "ratio_at_zero": round(_loans_to_funds(eng, NEED_YEAR, trial({seg: 0.0 for seg in PREMIUM_PATHS}))[0], 6)}
    say(f"volumes.funds_share_drift: нужда баланса {100 * need_w:+.2f} п.п. в год (кредиты к средствам клиентов модальной клетки на конец {NEED_YEAR} года = "
        f"якорь {anchor:.4f}; при нуле — {out['funds']['ratio_at_zero']:.4f}, при фактах — {out['funds']['ratio_at_facts']:.4f}); середина с фактами: "
        + ", ".join(f"{seg} {100 * v:+.2f}" for seg, v in levels.items()) + f" → на конец {NEED_YEAR} года {out['funds']['ratio_at_centre']:.4f}")


def t2_traj(eng: Engine, ctx, cell) -> dict:
    tl = ctx.timeline
    t2_0 = float(eng.book.get("capital.n20.t2")[tl.period(0)])
    q_flat = tl.index(T2_FLAT_UNTIL)
    rwa = cell.quarters["rwa"]
    last_year = str(tl.last_year)
    traj = {tl.period(0): t2_0, T2_FLAT_UNTIL[:4]: t2_0}
    tail = []
    for q in range(q_flat + 1, tl.Q + 1):
        v = t2_0 * float(rwa[q]) / float(rwa[q_flat])
        if tl.period(q).startswith(last_year):
            tail.append(v)
        else:
            traj[tl.period(q)] = v
    traj[last_year] = sum(tail) / len(tail)
    traj["LT"] = traj[last_year]
    return traj


def step_t2(eng: Engine, out: dict) -> None:
    """Дополнительный капитал: плоско по квартал ступени, далее доля RWA модальной клетки этого квартала."""
    traj = None
    for _ in range(4):                                         # траектория → норматив → дивиденд → баланс → RWA: до неподвижной
        ctx, cell = eng.cell()
        new = t2_traj(eng, ctx, cell)
        moved = 1.0 if traj is None else max(abs(new[k] - traj[k]) for k in new)
        traj = new
        eng.overrides["capital.n20.t2"] = traj
        if moved < 0.01:
            break
    ctx, cell = eng.cell()
    tl = ctx.timeline
    q_flat = tl.index(T2_FLAT_UNTIL)
    out["t2"] = {"cell": cell.label, "flat_until": T2_FLAT_UNTIL, "rwa_flat": round(float(cell.quarters["rwa"][q_flat]), 1),
                 "share": float(traj[tl.period(0)]) / float(cell.quarters["rwa"][q_flat]),
                 "rwa_end": round(float(cell.quarters["rwa"][tl.Q]), 1), "t2_end": round(traj["LT"], 1)}
    say(f"capital.n20.t2: {traj[tl.period(0)]:.1f} по {T2_FLAT_UNTIL}; далее {100 * out['t2']['share']:.3f} % RWA клетки {cell.label} "
        f"(RWA {out['t2']['rwa_flat']:.0f} → {out['t2']['rwa_end']:.0f}); {tl.last_year}: {out['t2']['t2_end']:.1f}")


def deduction_parts(tl, *, eta: float, rwa0: float, growth: float = DED_GROWTH_PER_Q, release: float = DTA_RELEASE_PER_YEAR,
                    by_quarter: bool = False, growth_share: float | None = None) -> dict[str, list[float]]:
    """Слагаемые пути вычета по кварталам q = 0…Q (общие для всех сценариев): `fixed` — постоянная доля роста вычетов, млрд ₽
    (доля × накопленный рост × RWA якоря); `release` — высвобождение ОНА, млрд ₽ (со знаком минус); `growing` — растущая с RWA
    часть роста вычетов, доли RWA; `release_pp` — высвобождение в п.п. RWA (накопленно, со знаком плюс). `growth_share` — доля роста
    вычетов, постоянная в рублях (по умолчанию η: решение № 3, п. 6.2(1) и № 4, п. 3.3). `by_quarter` — второе чтение темпа
    высвобождения: копится по четверти годового шага за квартал (к концу года — то же число), а не действует с 1-го квартала года."""
    q_from, q_to = tl.index(DED_GROWTH_QUARTERS[0]), tl.index(DED_GROWTH_QUARTERS[1])
    share = eta if growth_share is None else float(growth_share)
    out = {"fixed": [0.0], "release": [0.0], "growing": [0.0], "release_pp": [0.0], "grown_pp": [0.0]}
    for q in range(1, tl.Q + 1):
        year = tl.year(q)
        a = growth * max(0, min(q, q_to) - q_from + 1)                     # накопленный рост вычетов, п.п.
        freed = release * max(0, year - (DTA_RELEASE_FROM - 1))            # высвобождение, п.п. накопленно (значение года — с 1-го квартала)
        if by_quarter and year >= DTA_RELEASE_FROM:
            freed -= release * (1.0 - int(tl.period(q)[-1]) / 4.0)         # второе чтение: по четверти шага за квартал
        out["fixed"].append(share * a * rwa0)
        out["release"].append(-freed * rwa0)
        out["growing"].append((1.0 - share) * a)
        out["release_pp"].append(freed)
        out["grown_pp"].append(a)
    return out


def scenario_at(scenario, scenario_from: int, year: int) -> float:
    """Регуляторный вычет сценария в году `year`, доли RWA: число — с года `scenario_from`; словарь {год: значение} — по годам (у
    «послабления» — смесь трёх сценариев долей возврата года, решение № 5, п. 3.3; год расхождения сценариев в словаре свой)."""
    if isinstance(scenario, dict):
        return float(scenario.get(year, 0.0))
    return float(scenario) if year >= scenario_from else 0.0


def relief_deduction(book, tl, mix: bool = True) -> dict[int, float]:
    """Регуляторный вычет сценария «послабление» по годам сетки (решение № 5, п. 3.3): до года расхождения — ноль (2026 — факт, 2027–2028 —
    снятие надбавок); с него — доля возврата года надбавки за значимость × смесь вычетов трёх сценариев с вероятностями строки без кризиса;
    `mix=False` — прежняя форма (возврат к «по графику»: вычета нет)."""
    row = book.get(f"joint.reg_prob_given_regime.{RELIEF_WEIGHTS_ROW}")
    p = {s: float(row[s]) for s in RELIEF_MIX}
    level = sum(p[s] * SCENARIO_DEDUCTION.get(s, 0.0) for s in RELIEF_MIX) / sum(p.values())
    ret = RELIEF_RETURN[RELIEF_DEDUCTION_RETURN]
    out = {}
    for y in range(tl.anchor_year, tl.last_year + 1):
        if not mix or y < RELIEF_FROM:
            out[y] = 0.0
        elif y >= int(ret["LT_from"]):
            out[y] = round(level, 12)
        else:
            out[y] = round(float(ret[str(y)]) * level, 12)
    return out


def scenario_of(book, tl, scenario_id: str, relief_mix: bool = True):
    """Регуляторный вычет сценария книги: число (с года расхождения) или, у «послабления», словарь по годам."""
    if scenario_id == RELIEF_ID:
        return relief_deduction(book, tl, relief_mix)
    return SCENARIO_DEDUCTION.get(scenario_id, 0.0)


def deduction_fg(tl, *, eta: float, rwa0: float, growth: float = DED_GROWTH_PER_Q, release: float = DTA_RELEASE_PER_YEAR,
                 scenario=0.0, scenario_from: int = SCENARIO_DEDUCTION_FROM, ruble: tuple[str, ...] = ("growth", "release"),
                 by_quarter: bool = False, growth_share: float | None = None) -> tuple[list[float], list[float]]:
    """Слагаемые пути вычета сценария по кварталам q = 0…Q: F — сумма в рублях, млрд ₽; G — растущая часть, доли RWA.
    `ruble` — какие слагаемые считаются суммой в рублях (оба — правило решения № 3, п. 6.2; слагаемое вне перечня идёт
    прежней формой — в п.п. RWA: так меряется вклад каждого слагаемого в сдвиг оценки). Слагаемого «деньги выпуска вне капитала
    норматива» нет (решение № 4, п. 3.1: выпуск — притоком капитала, шаг issue)."""
    parts = deduction_parts(tl, eta=eta, rwa0=rwa0, growth=growth, release=release, by_quarter=by_quarter, growth_share=growth_share)
    f, g = [0.0], [0.0]
    for q in range(1, tl.Q + 1):
        year = tl.year(q)
        fixed = parts["fixed"][q] if "growth" in ruble else 0.0
        f.append(fixed + (parts["release"][q] if "release" in ruble else 0.0))
        g.append((parts["growing"][q] if "growth" in ruble else parts["grown_pp"][q]) + scenario_at(scenario, scenario_from, year)
                 - (0.0 if "release" in ruble else parts["release_pp"][q]))
    return f, g


def deduction_traj(tl, rwa, f: list[float], g: list[float]) -> dict:
    """Траектория вычета сценария в п.п. RWA: F(t) / RWA(t) + G(t); ключи — кварталы, год last_period — среднее его кварталов."""
    traj, tail = {tl.period(0): 0.0}, []
    for q in range(1, tl.Q + 1):
        v = f[q] / float(rwa[q]) + g[q]
        if tl.year(q) == tl.last_year:
            tail.append(v)
        else:
            traj[tl.period(q)] = round(v, 6)
    traj[str(tl.last_year)] = round(sum(tail) / len(tail), 6)
    traj["LT"] = traj[str(tl.last_year)]
    traj["LT_from"] = tl.last_year
    return traj


def issue_volume(n_iss: float, share_count_adj: float) -> float:
    """Объём выпуска по известной цене, млрд ₽: поправка делителя × размещённые акции (млн) × цена."""
    return round(float(share_count_adj) * float(n_iss) * ISSUE_PRICE / 1000.0, 2)


