def months_of(eng: Engine, period: str) -> list[dict]:
    """Месячные результаты фактов за квартал `period` (узел mgmt_quarterly.monthly)."""
    year, qn = int(period[:4]), int(period[-1])
    want = {f"{year}-{m:02d}" for m in range(3 * qn - 2, 3 * qn + 1)}
    return [m for m in eng.facts.file("mgmt_quarterly").get("monthly") or [] if m["month"] in want]


def month_sum(rows: list[dict], name: str) -> float:
    return sum(float(r[name]["v"]) for r in rows)


def fact_quarter(eng: Engine, period: str) -> dict:
    """Квартал по месячным фактам: потоки — известные месяцы × 3 / число месяцев; маржа — среднее месяцев."""
    rows = months_of(eng, period)
    if len(rows) < 2:
        raise RuntimeError(f"в фактах меньше двух месяцев квартала {period}: путь года якоря не вывести")
    k = 3.0 / len(rows)
    return {"months": [r["month"] for r in rows], "scale": k,
            "nim": sum(float(r["nim_m"]["v"]) for r in rows) / len(rows),
            "nii": month_sum(rows, "nii_m") * k, "fees": month_sum(rows, "nci_m") * k,
            "opex": -month_sum(rows, "opex_m") * k, "llp": -month_sum(rows, "provisions_m") * k,
            "ni": month_sum(rows, "net_profit_m") * k, "other_income_bank": month_sum(rows, "other_income_m") * k}


